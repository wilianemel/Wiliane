-- ============================================================================
-- PARTE 2 -- RPC search_claimable_venues (para /empresa/reivindicar)
-- ============================================================================

create or replace function public.search_claimable_venues(search_query text)
returns table (
  id uuid,
  name text,
  category text,
  city text,
  neighborhood text,
  cover_image_url text
)
language plpgsql
security definer
set search_path = ''
as $func$
declare
  v_user_id uuid;
  v_query text;
begin
  -- Nunca confia só no grant de EXECUTE -- checa auth.uid() de verdade
  -- dentro da própria função.
  v_user_id := auth.uid();
  if v_user_id is null then
    raise exception 'É necessário estar autenticado para buscar estabelecimentos.';
  end if;

  v_query := trim(coalesce(search_query, ''));
  if length(v_query) < 2 then
    raise exception 'Digite ao menos 2 caracteres para buscar.';
  end if;

  return query
    select v.id, v.name, v.category, v.city, v.neighborhood, v.cover_image_url
    from public.venues v
    where v.name ilike '%' || v_query || '%'
      and not exists (
        select 1
        from public.venue_members vm
        where vm.venue_id = v.id
          and vm.is_active = true
      )
    order by v.name
    limit 20;
end;
$func$;

comment on function public.search_claimable_venues(text) is
  'Busca estabelecimentos (publicados ou não) sem nenhum vínculo ativo em venue_members, para /empresa/reivindicar. SECURITY DEFINER só para alcançar rascunhos sem owner -- nunca aceita nem expõe dado fora das 6 colunas declaradas, nunca cria vínculo. Exige autenticação e ao menos 2 caracteres de busca.';

revoke all on function public.search_claimable_venues(text) from public;
revoke all on function public.search_claimable_venues(text) from anon;
grant execute on function public.search_claimable_venues(text) to authenticated;

